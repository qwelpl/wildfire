"""Builds the word lists from an English dictionary and word frequencies.

  js/words.js        every word the game accepts
  tools/common.txt   familiar words the board generator plans with

Usage: python words.py path/to/an-array-of-english-words/index.json
Needs: pip install wordfreq nltk, plus the WordNet corpus
"""
import json
import sys
from pathlib import Path

from nltk.corpus import wordnet as wn
from wordfreq import zipf_frequency

ACCEPT_ZIPF = 1.5   # lenient: anything a player could reasonably know
COMMON_ZIPF = 3.3   # what par is built from

root = Path(__file__).resolve().parent.parent
words = json.load(open(sys.argv[1]))
words = sorted({w for w in words if w.isalpha() and w.islower() and 3 <= len(w) <= 16})
freq = {w: zipf_frequency(w, 'en') for w in words}

accepted = [w.upper() for w in words if freq[w] >= ACCEPT_ZIPF]
# WordNet knows real vocabulary but not brands and most names (IOS, HICKS).
common = [w.upper() for w in words if freq[w] >= COMMON_ZIPF and wn.morphy(w)]

(root / 'js' / 'words.js').write_text(
    '// Generated by tools/words.py. Do not edit by hand.\n'
    f'window.WILDFIRE_WORDS = "{" ".join(accepted)}";\n'
    f'window.WILDFIRE_COMMON = "{" ".join(common)}";\n')
(root / 'tools' / 'common.txt').write_text('\n'.join(common) + '\n')
print(f'{len(accepted)} accepted, {len(common)} common')
